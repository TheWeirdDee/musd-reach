// Exports ABIs from Foundry artifacts into packages/sdk/src/abis.ts (typed `as const`).
import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "packages/contracts/out");
const contracts = [
  ["ReachSavingsWrapper", "reachSavingsWrapperAbi"],
  ["ReachSourceGateway", "reachSourceGatewayAbi"],
  ["ReachDestinationGateway", "reachDestinationGatewayAbi"],
  ["RemoteWrapperReceipt", "remoteWrapperReceiptAbi"],
  ["ReachNavOracle", "reachNavOracleAbi"],
  ["IMUSDSavingsRate", "musdSavingsRateAbi", "IMUSDSavingsRate.sol"],
  ["IWormhole", "wormholeCoreAbi", "IWormhole.sol"],
];

let ts = "// Generated by scripts/export-abis.mjs from Foundry artifacts. Do not edit.\n\n";
for (const [name, exportName, file] of contracts) {
  const artifact = JSON.parse(readFileSync(join(out, file ?? `${name}.sol`, `${name}.json`), "utf8"));
  ts += `export const ${exportName} = ${JSON.stringify(artifact.abi, null, 2)} as const;\n\n`;
}
writeFileSync(join(root, "packages/sdk/src/abis.ts"), ts);
console.log(`wrote ${contracts.length} ABIs`);
